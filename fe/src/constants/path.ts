  EVENTS: 'events',
  EVENT_DETAIL: 'events/:id',
  SERVICES: 'services',
  SERVICE_DETAIL: 'services/:id',
  TRIPS: 'trips',
  ADMIN: 'admin',
  LOGIN: 'login',
